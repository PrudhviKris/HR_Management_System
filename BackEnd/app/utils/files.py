"""Secure upload handling: extension allow-list, magic-byte sniffing, size cap, random storage names,
no user-controlled paths, files kept outside any static/web root and only served via authorised endpoints."""

import hashlib
import re
import uuid
from pathlib import Path

from fastapi import UploadFile

from app.core.config import settings
from app.exceptions import ValidationError

# ext -> (mime, magic-byte prefixes)
ALLOWED: dict[str, tuple[str, tuple[bytes, ...]]] = {
    ".pdf": ("application/pdf", (b"%PDF-",)),
    ".png": ("image/png", (b"\x89PNG\r\n\x1a\n",)),
    ".jpg": ("image/jpeg", (b"\xff\xd8\xff",)),
    ".jpeg": ("image/jpeg", (b"\xff\xd8\xff",)),
    ".docx": (
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        (b"PK\x03\x04",),
    ),
}

DOCUMENTS_DIR = settings.UPLOAD_DIR / "documents"
PAYSLIPS_DIR = settings.UPLOAD_DIR / "payslips"
CHUNK = 64 * 1024


def ensure_dirs() -> None:
    DOCUMENTS_DIR.mkdir(parents=True, exist_ok=True)
    PAYSLIPS_DIR.mkdir(parents=True, exist_ok=True)


def safe_display_name(name: str) -> str:
    name = Path(name or "file").name  # strip any directory components
    name = re.sub(r"[^A-Za-z0-9._ -]", "_", name).strip(" .") or "file"
    return name[:200]


async def save_upload(upload: UploadFile) -> dict:
    original = safe_display_name(upload.filename or "")
    ext = Path(original).suffix.lower()
    if ext not in ALLOWED:
        raise ValidationError(f"File type not allowed. Allowed: {', '.join(sorted(ALLOWED))}", code="invalid_file_type")
    mime, magics = ALLOWED[ext]
    max_bytes = settings.MAX_UPLOAD_MB * 1024 * 1024

    ensure_dirs()
    stored = f"{uuid.uuid4().hex}{ext}"
    target = DOCUMENTS_DIR / stored
    digest, size, head = hashlib.sha256(), 0, b""
    try:
        with target.open("wb") as fh:
            while chunk := await upload.read(CHUNK):
                if not head:
                    head = chunk[:16]
                    if not any(head.startswith(m) for m in magics):
                        raise ValidationError("File content does not match its extension", code="invalid_file_content")
                size += len(chunk)
                if size > max_bytes:
                    raise ValidationError(f"File exceeds the {settings.MAX_UPLOAD_MB} MB limit", code="file_too_large")
                digest.update(chunk)
                fh.write(chunk)
        if size == 0:
            raise ValidationError("File is empty", code="empty_file")
    except Exception:
        target.unlink(missing_ok=True)
        raise
    return {
        "original_filename": original,
        "stored_filename": stored,
        "content_type": mime,
        "size_bytes": size,
        "sha256": digest.hexdigest(),
    }


def document_path(stored_filename: str) -> Path:
    # stored names are generated by us, but guard against tampering anyway
    if not re.fullmatch(r"[0-9a-f]{32}\.[a-z]{3,4}", stored_filename):
        raise ValidationError("Invalid file reference")
    return DOCUMENTS_DIR / stored_filename
